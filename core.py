# ── Motion timing ─────────────────────────────────────────────────────────────
# Seconds, gathered here so the widget's rhythm can be retuned in one place.
# These used to be a blink count and a frame delay, which could only make the
# old square wave longer or shorter -- never softer.
#
# The bands are the ones the eye actually distinguishes: under ~150ms reads as
# instant, ~200-300ms as responsive, ~350-500ms as deliberate. Hover sits in
# the first band because a control that takes longer than the pointer does
# feels laggy; a mode switch sits in the second because it is a decision the
# user made and wants to see land.
